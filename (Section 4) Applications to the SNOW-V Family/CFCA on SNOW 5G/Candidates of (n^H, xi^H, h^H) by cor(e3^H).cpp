/**
 * 16-bit modular addition automaton.
 *
 * @param input1  first input mask  (v)
 * @param input2  second input mask (w)
 * @param output  output mask       (u)
 * @return signed correlation value, or -100.0 if zero correlation is forced
 */
double automaton16(uint32_t input1, uint32_t input2, uint32_t output)
{
    double k = 0;           // exponent counter for solid-arrow transitions
    int e = 0;              // automaton state (0 or 1)
    int t;
    int flag;
    double sign = 1.0;      // sign factor due to sign-changing transitions

    for (t = 0; t < 16; t++)
    {
        // transition label mu_i = u_i*4 + v_i*2 + w_i
        flag = ((output >> (15 - t)) & 1) * 4 +
               ((input1 >> (15 - t)) & 1) * 2 +
               ((input2 >> (15 - t)) & 1);

        if (e == 0)
        {
            if (flag == 7)
                e = 1;
            else if (flag == 0)
                e = 0;
            else
                return -100.0;   // non-zero correlation impossible
        }
        else   // e == 1
        {
            if ((flag == 0) || (flag == 3) || (flag == 5) || (flag == 6))
            {
                e = 1;
                k++;               // solid arrow while staying in e1
            }
            else
            {
                e = 0;
                k++;               // solid arrow while moving from e1 to e0
            }
            if ((flag == 3) || (flag == 4))
                sign = -sign;      // sign change
        }
    }
    return sign * pow(2.0, -k);
}

/* Candidate set for n (upper 16-bit block) */
uint32_t N[6] = {0x81e8, 0xc1e8, 0x81ee, 0xa1e8, 0xc1ee, 0xe1e8};

int main()
{
    uint32_t gamma = 0x81ec;   // fixed output mask for the upper block
    char filename[20];
    sprintf(filename, "0x%04x.txt", gamma);
    FILE *fp1 = fopen(filename, "w");

    /* Parallel enumeration over all combinations of table_idx, n, xi, and h */
    #pragma omp parallel for collapse(4)
    for (int table_idx = 0; table_idx < 4; table_idx++)
    {
        for (int i4 = 0; i4 < 6; i4++)
        {
            for (int i3 = 0; i3 < 128; i3++)
            {
                for (int i2 = 0; i2 < 128; i2++)
                {
                    uint32_t xi = value[table_idx][i2];
                    uint32_t h  = value[table_idx][i3];
                    uint32_t n  = N[i4];
                    double ce3 = 0.0;

                    /* Enumerate the active high byte of theta (low byte zero) */
                    #pragma omp simd reduction(+:ce3)
                    for (int i1 = 128; i1 < 256; i1++)
                    {
                        uint32_t theta = i1 << 8;
                        double c1 = automaton16(theta, n, gamma);
                        double c2 = automaton16(xi, h, theta);
                        if ((c1 > -100) && (c2 > -100))
                            ce3 += c1 * c2;
                    }

                    double cor = ce3;
                    if (fabs(cor) > pow(2.0, -15))   // only output significant correlations
                    {
                        double cor_exp = log2(fabs(cor));
                        int cor_sign = (cor > 0) ? 1 : -1;
                        #pragma omp critical
                        {
                            printf("%d, 0x%04x, 0x%04x, 0x%04x, %.4f, %d\n",
                                   table_idx, n, xi, h, cor_exp, cor_sign);
                            fprintf(fp1, "%d, 0x%04x, 0x%04x, 0x%04x, %.4f, %d\n",
                                    table_idx, n, xi, h, cor_exp, cor_sign);
                        }
                    }
                }
            }
        }
    }

    fclose(fp1);
    return 0;
}